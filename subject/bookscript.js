const opebBtn = document.getElementById('open');
const resultBox = document.getElementById('bookresult');
const questionInput = document.querySelector('input[type="text"]');

opebBtn.addEventListener('click', function(e) {
    e.preventDefault();

    if (questionInput.value.trim() === "") {
        return resultBox.value = "오른쪽으로 세 번 돌고 책을 다시 펼치세요.";
    }

    const random = Math.floor(Math.random() * booktext.length);
    resultBox.value = booktext[random];
    questionInput.value = "";
});